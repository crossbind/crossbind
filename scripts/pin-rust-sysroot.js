#!/usr/bin/env node
// Writes the published sysroot artifact into rustSysrootPin.js, so a host build (RUNNER=LOCAL)
// downloads exactly the archive a release produced instead of rebuilding std on nightly. The
// source is the pin file the publish workflow emits next to the uploaded archive - never a hash
// computed from whatever happens to sit in tooling/docker/dist locally.
//
//   gh run download <run id> -n sysroot-pin -D /tmp/pin
//   node scripts/pin-rust-sysroot.js /tmp/pin/sysroot-pin.json

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const TARGET = path.join(ROOT, 'core', 'crossbind', 'src', 'utils', 'rustSysrootPin.js');
const VERSION_FILE = path.join(ROOT, 'tooling', 'docker', 'VERSION');

const fail = (message) => {
    console.error(`pin-rust-sysroot: ${message}`);
    process.exit(1);
};

const pinPath = process.argv[2];
if (!pinPath) fail('pass the sysroot-pin.json produced by the publish workflow');
if (!fs.existsSync(pinPath)) fail(`${pinPath} does not exist`);

let pin;
try {
    pin = JSON.parse(fs.readFileSync(pinPath, 'utf8'));
} catch (e) {
    fail(`${pinPath} is not valid JSON: ${e.message}`);
}

const expected = fs.readFileSync(VERSION_FILE, 'utf8').trim();
if (pin.version !== expected) {
    fail(`the pin was produced for ${pin.version}, but tooling/docker/VERSION says ${expected}.\n`
        + '  Publish the images for this version first, or check out the commit that produced the pin.');
}
if (!/^https:\/\//.test(pin.url ?? '')) fail(`the artifact url must be https, got ${pin.url}`);
if (!/^[0-9a-f]{64}$/.test(pin.sha256 ?? '')) fail(`the sha256 is not a 64-character hex digest: ${pin.sha256}`);

const body = `// Generated by scripts/pin-rust-sysroot.js - do not edit by hand.
//
// The Rust sysroot artifact a host build (RUNNER=LOCAL) downloads instead of rebuilding std the
// nightly way. Verified against its sha256 and against the host compiler before anything links:
// prebuilt rlibs are only consumable by the exact rustc that produced them.
export default {
    version: '${pin.version}',
    url: '${pin.url}',
    sha256: '${pin.sha256}',
};
`;

fs.writeFileSync(TARGET, body);
console.log(`pin-rust-sysroot: ${path.relative(ROOT, TARGET)}`);
console.log(`  version  ${pin.version}`);
console.log(`  url      ${pin.url}`);
console.log(`  sha256   ${pin.sha256}`);
