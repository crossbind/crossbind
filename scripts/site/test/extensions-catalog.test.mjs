import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import test from 'node:test';
import { buildExtensionsCatalog, readExtensionsTree, renderExtensionsModule } from '../build-extensions-catalog.mjs';

// A repository of the extensions given, each a folder of extensions/ with its package.json.
function treeOf(t, manifests) {
    const root = fs.mkdtempSync(path.join(os.tmpdir(), 'crossbind-extensions-catalog-'));
    t.after(() => fs.rmSync(root, { recursive: true, force: true }));
    for (const manifest of manifests) {
        const folder = path.join(root, 'extensions', manifest.name.split('/').at(-1));
        fs.mkdirSync(folder, { recursive: true });
        fs.writeFileSync(path.join(folder, 'package.json'), JSON.stringify(manifest));
    }
    return root;
}

test('the catalog leaves out the extensions an app has by having the host', (t) => {
    const root = treeOf(t, [
        { name: '@crossbind/extension-clipboard', description: 'crossbind app extension: the clipboard.' },
        { name: '@crossbind/extension-dialog', description: 'crossbind app extension: the dialogs.' },
    ]);
    fs.mkdirSync(path.join(root, 'core', 'app-host'), { recursive: true });
    fs.writeFileSync(
        path.join(root, 'core', 'app-host', 'package.json'),
        JSON.stringify({ dependencies: { '@crossbind/extension-dialog': 'workspace:^' } }),
    );

    assert.deepEqual(
        readExtensionsTree(root).map(({ name }) => name),
        ['@crossbind/extension-clipboard'],
    );
});

const registryOf = (tags) => ({ distTags: async (name) => tags[name] ?? null });

test("the repository's own extensions have the name and the summary the Apps guide shows", () => {
    const extensions = readExtensionsTree();

    assert.ok(extensions.some((extension) => extension.name === '@crossbind/extension-clipboard'));
    for (const extension of extensions) {
        assert.match(extension.name, /^@crossbind\/extension-[a-z0-9-]+$/);
        assert.match(extension.summary, /^[A-Z]/, extension.name);
    }
});

test('an extension takes the version npm serves on the dist-tag, or null where it serves none, and a private one is left out', async (t) => {
    const root = treeOf(t, [
        { name: '@crossbind/extension-clipboard', description: "crossbind app extension: the system clipboard's text." },
        { name: '@crossbind/extension-share', description: 'crossbind app extension: the share sheet.' },
        { name: '@crossbind/example-sample', private: true, description: 'A sample.' },
    ]);
    const log = [];

    const catalog = await buildExtensionsCatalog({
        root,
        distTag: 'beta',
        registry: registryOf({ '@crossbind/extension-clipboard': { beta: '2.0.0-beta.69', latest: '1.0.0' } }),
        log: (line) => log.push(line),
    });

    assert.deepEqual(catalog, {
        schemaVersion: 1,
        source: 'live',
        distTag: 'beta',
        extensions: [
            { name: '@crossbind/extension-clipboard', summary: "The system clipboard's text.", version: '2.0.0-beta.69' },
            { name: '@crossbind/extension-share', summary: 'The share sheet.', version: null },
        ],
    });
    assert.deepEqual(log, ['@crossbind/extension-share: not on npm beta']);
});

test('a fixture build is marked as such, and its module is the catalog', async (t) => {
    const root = treeOf(t, [{ name: '@crossbind/extension-clipboard', description: 'crossbind app extension: the clipboard.' }]);
    const fixture = { npm: { packages: { '@crossbind/extension-clipboard': { distTags: { beta: '2.0.0-beta.69' } } } } };

    const catalog = await buildExtensionsCatalog({ root, distTag: 'beta', fixture });

    assert.equal(catalog.source, 'fixture');
    assert.equal(catalog.extensions[0].version, '2.0.0-beta.69');
    assert.match(renderExtensionsModule(catalog), /^\/\/ Generated by scripts\/site\/build-extensions-catalog\.mjs[^\n]*\nexport default \{/);
});

test('an extension without a description stops the site build', (t) => {
    const root = treeOf(t, [{ name: '@crossbind/extension-bare' }]);

    assert.throws(() => readExtensionsTree(root), /@crossbind\/extension-bare has no description/);
});
