import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { test } from 'node:test';
import { readExtensionPages, renderExtensionPagesModule } from '../build-extension-pages.mjs';

function treeOf(t, name, readme) {
    const root = fs.mkdtempSync(path.join(os.tmpdir(), 'crossbind-extension-pages-'));
    t.after(() => fs.rmSync(root, { recursive: true, force: true }));
    const folder = path.join(root, 'extensions', name);
    fs.mkdirSync(folder, { recursive: true });
    fs.writeFileSync(
        path.join(folder, 'package.json'),
        JSON.stringify({ name: `@crossbind/extension-${name}`, homepage: `https://example.com/${name}` }),
    );
    fs.writeFileSync(path.join(folder, 'README.md'), readme);
    return root;
}

test("an extension's page is its README: the line under its title, then its sections, with the site's links its own", (t) => {
    const root = treeOf(
        t,
        'dialog',
        '# @crossbind/extension-dialog\n\nThe dialogs.\n\n## Use\n\n```js\nawait dialog.open();\n```\n\n[The guide](https://crossbind.dev/guide/extensions/#replace) shows how.\n',
    );

    assert.deepEqual(readExtensionPages(root), [
        {
            name: 'dialog',
            package: '@crossbind/extension-dialog',
            homepage: 'https://example.com/dialog',
            lede: 'The dialogs.',
            blocks: [
                { type: 'h2', id: 'use', text: 'Use' },
                { type: 'code', file: 'JavaScript', code: 'await dialog.open();' },
                { type: 'p', text: '[The guide](/guide/extensions/#replace) shows how.' },
            ],
        },
    ]);
});

test('a README that is not titled with its package, or has no line under its title, stops the build', (t) => {
    assert.throws(() => readExtensionPages(treeOf(t, 'menu', '# Menu\n\nThe menus.\n')), /opens with no # @crossbind\/extension-menu/);
    assert.throws(() => readExtensionPages(treeOf(t, 'power', '# @crossbind/extension-power\n\n## Use\n')), /has no line under its title/);
});

test("the repository's extensions each have a page, which the module holds", () => {
    const pages = readExtensionPages();
    const folders = fs.readdirSync(new URL('../../../extensions/', import.meta.url));
    assert.deepEqual(
        pages.map(({ name }) => name),
        folders.toSorted((left, right) => left.localeCompare(right, 'en')),
    );
    for (const page of pages)
        assert.ok(
            page.blocks.some((block) => block.type === 'h2'),
            page.name,
        );
    assert.match(renderExtensionPagesModule(pages), /^\/\/ Generated by scripts\/site\/build-extension-pages\.mjs[^\n]*\nexport default \[/);
});
