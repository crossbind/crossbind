import fs from 'node:fs';
import path from 'node:path';
import { releaseNotesBlocks } from '../release/release-notes-blocks.mjs';
import { REPOSITORY_ROOT } from './build-ports-catalog.mjs';

// The site's page of each app extension, from its README, as the release notes are made: the line under its title is
// the page's lede and the rest its blocks, so that the site says what the package says. A link to the site itself
// becomes one of the site's own.

const SITE_LINK = /\]\(https:\/\/crossbind\.dev\//g;
// A code block's language, as the site's blocks name what a block holds.
const LANGUAGES = { sh: 'shell', js: 'JavaScript' };

export function readExtensionPages(root = REPOSITORY_ROOT) {
    const folder = path.join(root, 'extensions');
    return fs
        .readdirSync(folder, { withFileTypes: true })
        .filter((entry) => entry.isDirectory() && fs.existsSync(path.join(folder, entry.name, 'package.json')))
        .map((entry) => {
            const manifest = JSON.parse(fs.readFileSync(path.join(folder, entry.name, 'package.json'), 'utf8'));
            const file = `extensions/${entry.name}/README.md`;
            const [title, ...lines] = fs.readFileSync(path.join(root, file), 'utf8').replace(SITE_LINK, '](/').split('\n');
            if (title !== `# ${manifest.name}`) throw new Error(`${file} opens with no # ${manifest.name}, the title of its page.`);
            const blocks = releaseNotesBlocks(lines.join('\n'), file).map((block) =>
                block.type === 'code' ? { ...block, file: LANGUAGES[block.file] ?? block.file } : block,
            );
            const [lede, ...rest] = blocks;
            if (lede?.type !== 'p') throw new Error(`${file} has no line under its title, which its page opens with.`);
            return { name: entry.name, package: manifest.name, homepage: manifest.homepage, lede: lede.text, blocks: rest };
        })
        .sort((left, right) => left.name.localeCompare(right.name, 'en'));
}

export function renderExtensionPagesModule(pages) {
    return `// Generated by scripts/site/build-extension-pages.mjs before every site build. Do not edit.\nexport default ${JSON.stringify(pages, null, 4)};\n`;
}
