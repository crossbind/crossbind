import { spawn } from 'node:child_process';
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import {
    BUILD_TOKEN_ENVIRONMENT_VARIABLE,
    createFixtureClients,
    createLiveClients,
    FIXTURE_ENVIRONMENT_VARIABLE,
    renderSnapshotModule,
    resolveSiteRelease,
} from '../release/resolve-site-release.mjs';
import { buildPortsCatalog, renderCatalogModule } from './build-ports-catalog.mjs';
import { DEMOS_ROOT, MANIFEST_NAME } from './build-example-demos.mjs';
import { parseReleaseNotes } from '../release/release-lib.mjs';
import { releaseNotesBlocks } from '../release/release-notes-blocks.mjs';
import { assertChangelogCurrent, CHANGELOG_FILE, REPOSITORY_ROOT as CHANGELOG_ROOT, splitChangelog } from '../release/render-changelog.mjs';

// Everything the site needs from outside its own tree, resolved once per dev/build run:
// the verified release snapshot and the ports catalog with its npm publication state. Both are
// written as generated modules, then vite runs with a one-off token that vite.config.js checks,
// so a bare `vite build` cannot reuse files left behind by an earlier run. One fixture document
// (CROSSBIND_SITE_RELEASE_FIXTURE) feeds both for offline work; such a build is marked and
// refused by the deploy step.

const log = (message) => process.stderr.write(`${message}\n`);

async function loadChannel(configFile) {
    const { default: config } = await import(pathToFileURL(path.resolve(configFile)).href);
    if (!config || typeof config.channel !== 'string') throw new Error(`${configFile} must export { channel }.`);
    return config.channel;
}

function loadFixture(env) {
    const file = env[FIXTURE_ENVIRONMENT_VARIABLE];
    if (!file) return null;
    try {
        return JSON.parse(fs.readFileSync(path.resolve(file), 'utf8'));
    } catch (error) {
        throw new Error(`${FIXTURE_ENVIRONMENT_VARIABLE}=${file} is not a readable JSON fixture: ${error.message}`, { cause: error });
    }
}

// The changelog page is CHANGELOG.md, converted section by section. Two checks keep it honest:
// the generated region must match the notes in releases/crossbind/, and every released version's
// note in the tree must be the one published with it, so the page shows what shipped.
function buildChangelog(snapshot) {
    assertChangelogCurrent();
    const sections = splitChangelog(fs.readFileSync(CHANGELOG_FILE, 'utf8')).map((section) => ({
        version: section.version,
        blocks: releaseNotesBlocks(section.body, `CHANGELOG.md ${section.version}`),
    }));
    if (!sections.some((section) => section.version === snapshot.version)) {
        throw new Error(`CHANGELOG.md has no entry for ${snapshot.version}; add its release note and run pnpm changelog.`);
    }
    for (const entry of snapshot.history) {
        const file = path.join(CHANGELOG_ROOT, entry.releaseNotes.source);
        if (!fs.existsSync(file)) throw new Error(`${entry.releaseNotes.source} shipped with ${entry.version} but is missing from the tree.`);
        const local = releaseNotesBlocks(parseReleaseNotes(fs.readFileSync(file, 'utf8'), entry.releaseNotes.source).body, entry.releaseNotes.source);
        if (JSON.stringify(local) !== JSON.stringify(entry.releaseNotes.blocks)) {
            throw new Error(
                `${entry.releaseNotes.source} differs from the note published with ${entry.version} at ${entry.gitCommit}; the site shows what shipped.`,
            );
        }
    }
    return { sections };
}

export async function prepareSite({ channel, outDir, env = process.env }) {
    const fixture = loadFixture(env);
    if (fixture) log(`Resolving the site from fixture ${path.resolve(env[FIXTURE_ENVIRONMENT_VARIABLE])}; this build cannot be deployed.`);
    const clients = fixture ? createFixtureClients(fixture) : createLiveClients();
    const snapshot = await resolveSiteRelease({ channel, ...clients, source: fixture ? 'fixture' : 'live', log });
    const catalog = await buildPortsCatalog({ distTag: snapshot.distTag, fixture: fixture ?? undefined, log });

    const buildToken = crypto.randomUUID();
    fs.mkdirSync(outDir, { recursive: true });
    fs.writeFileSync(path.join(outDir, 'release-snapshot.js'), renderSnapshotModule(snapshot, { buildToken }));
    const changelog = buildChangelog(snapshot);
    fs.writeFileSync(
        path.join(outDir, 'changelog.js'),
        `// Generated by scripts/site/prepare-site.mjs before every site build. Do not edit.\nexport default ${JSON.stringify(changelog, null, 4)};\n`,
    );
    fs.writeFileSync(path.join(outDir, 'ports-catalog.js'), renderCatalogModule(catalog));
    // Live demos are built separately (build-example-demos.mjs); the page shows the ones present.
    const manifestFile = path.join(DEMOS_ROOT, MANIFEST_NAME);
    const demos = fs.existsSync(manifestFile) ? JSON.parse(fs.readFileSync(manifestFile, 'utf8')) : { builtAt: null, distTag: null, demos: [] };
    const missing = demos.demos.filter((demo) => !fs.existsSync(path.join(DEMOS_ROOT, demo.id, 'index.html')));
    if (missing.length)
        throw new Error(`demos.json lists ${missing.map((demo) => demo.id).join(', ')} but the files are missing; rerun the demo build.`);
    fs.writeFileSync(
        path.join(outDir, 'example-demos.js'),
        `// Generated by scripts/site/prepare-site.mjs before every site build. Do not edit.\nexport default ${JSON.stringify(demos, null, 4)};\n`,
    );
    log(
        `Prepared ${outDir}: crossbind@${snapshot.version} (${snapshot.channel}, ${snapshot.source}, ${snapshot.gitCommit}), ` +
            `${changelog.sections.length} changelog entries (${snapshot.history.length} verified), ${catalog.ports.length} port families, ${demos.demos.length} live demos.`,
    );
    return { snapshot, catalog, buildToken };
}

function runWithToken(command, token) {
    return new Promise((resolve, reject) => {
        const child = spawn(command[0], command.slice(1), {
            stdio: 'inherit',
            env: { ...process.env, [BUILD_TOKEN_ENVIRONMENT_VARIABLE]: token },
        });
        child.on('error', reject);
        child.on('exit', (code, signal) => resolve(signal ? 1 : (code ?? 1)));
    });
}

async function main(argv) {
    const separator = argv.indexOf('--');
    const options = separator === -1 ? argv : argv.slice(0, separator);
    const command = separator === -1 ? [] : argv.slice(separator + 1);
    const valueOf = (flag) => {
        const index = options.indexOf(flag);
        return index === -1 ? undefined : options[index + 1];
    };
    const configFile = valueOf('--config');
    if (!configFile) throw new Error('Pass --config <release.config.js>.');
    const outDir = path.resolve(valueOf('--out-dir') ?? 'generated');
    const { buildToken } = await prepareSite({ channel: await loadChannel(configFile), outDir });
    return command.length ? runWithToken(command, buildToken) : 0;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
    main(process.argv.slice(2))
        .then((code) => process.exit(code))
        .catch((error) => {
            process.stderr.write(`${error.message}\n`);
            process.exit(1);
        });
}
