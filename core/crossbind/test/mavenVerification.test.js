import { describe, expect, test } from 'vitest';
import { mergedVerification } from '../src/actions/mavenVerification.js';

const metadata = (components) => `<?xml version="1.0" encoding="UTF-8"?>
<verification-metadata xmlns="https://schema.gradle.org/dependency-verification">
   <configuration>
      <verify-metadata>true</verify-metadata>
   </configuration>
   <components>
${components}   </components>
</verification-metadata>
`;
const component = (group, name, version, artifacts) => `      <component group="${group}" name="${name}" version="${version}">
${artifacts.map(([file, sha]) => `         <artifact name="${file}">
            <sha256 value="${sha}" origin="Generated by Gradle"/>
         </artifact>
`).join('')}      </component>
`;

const BASE = metadata(component('androidx.webkit', 'webkit', '1.17.1', [['webkit-1.17.1.aar', 'a1']]));

describe('the verification metadata of an Android app whose extensions ask Maven for libraries', () => {
    test("lists the image's components and each extension's, in Gradle's order, each file once", () => {
        const inject = metadata(component('javax.inject', 'javax.inject', '1', [['javax.inject-1.jar', 'b1'], ['javax.inject-1.pom', 'b2']]));
        const again = metadata(component('javax.inject', 'javax.inject', '1', [['javax.inject-1.jar', 'b1']]));
        expect(mergedVerification(BASE, [{ name: 'probe', xml: inject }, { name: 'other', xml: again }])).toBe(metadata([
            component('androidx.webkit', 'webkit', '1.17.1', [['webkit-1.17.1.aar', 'a1']]),
            component('javax.inject', 'javax.inject', '1', [['javax.inject-1.jar', 'b1'], ['javax.inject-1.pom', 'b2']]),
        ].join('')));
    });

    test('refuses other checksums of a file, a trust of files left unchecked and metadata of no component', () => {
        const other = metadata(component('androidx.webkit', 'webkit', '1.17.1', [['webkit-1.17.1.aar', 'ff']]));
        expect(() => mergedVerification(BASE, [{ name: 'probe', xml: other }]))
            .toThrow("crossbind: the extension probe gives webkit-1.17.1.aar of androidx.webkit:webkit:1.17.1 other checksums than the android-app image's verification metadata does.");
        const trusting = metadata('').replace('</configuration>', '   <trusted-artifacts><trust group="com.example"/></trusted-artifacts>\n   </configuration>');
        expect(() => mergedVerification(BASE, [{ name: 'probe', xml: trusting }]))
            .toThrow("crossbind: the extension probe's verification metadata trusts files Gradle would then leave unchecked, which no extension's may.");
        expect(() => mergedVerification(BASE, [{ name: 'probe', xml: metadata('') }]))
            .toThrow("crossbind: the extension probe's verification metadata lists no component, as Gradle's --write-verification-metadata sha256 writes them.");
    });
});
